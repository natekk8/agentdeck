def normalize_lang(lang):
    value = str(lang or DEFAULT_LANG).strip().lower()
    return value if value in SUPPORTED_LANGS else DEFAULT_LANG


def tr(lang, key, **fmt):
    code = normalize_lang(lang)
    table = STRINGS.get(code, STRINGS[DEFAULT_LANG])
    text = table.get(key) or STRINGS[DEFAULT_LANG].get(key) or key
    return text.format(**fmt) if fmt else text
